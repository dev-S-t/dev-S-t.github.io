// Writes mark.js: the mark from tools/logo/logo-gen.cjs as data the films can use in the browser and in Node:
// the five brush outlines and the dry-brush streaks (to draw the finished mark), and the centre line of every stroke
// (so a figure can settle onto the mark's exact geometry). Units are the mark's own: a 0..100 box.
const fs = require('fs'), path = require('path');
const G = require(path.resolve(__dirname, '../../../tools/logo/logo-gen.cjs'));
const { paths, gaps } = G.build({ samples: 220, decimals: 2 });
const R = G.RINGS, N = 160, line = (f) => Array.from({ length: N + 1 }, (_, i) => f(i / N).map((v) => Math.round(v * 100) / 100));
const fig = G.figure(1);
const lines = {
  loop: line(G.arc(...R.loop, G.GAP, G.OPEN, 1, 0.025)),
  arms: line(G.arc(...R.arms, G.GAP, G.OPEN, 2, 0.03)),
  head: line(G.arc(...R.head, G.GAP, G.OPEN, 3, 0.03)),
  spine: line(fig.spine[0]),
  legs: line(fig.legs[0])
};
const data = { paths, gaps, lines, widths: { loop: 5.4, arms: 3.6, head: 4.3, spine: 3.4, legs: 3.4 }, rings: R, gap: G.GAP, open: G.OPEN };
fs.writeFileSync(path.join(__dirname, 'mark.js'), `// generated by make-mark.cjs from tools/logo/logo-gen.cjs; do not edit\n(function (root, d) { if (typeof module === 'object' && module.exports) module.exports = d; else root.Mark = d; })(this, ${JSON.stringify(data)});\n`);
console.log('mark.js', Math.round(fs.statSync(path.join(__dirname, 'mark.js')).size / 1024) + ' KB');
